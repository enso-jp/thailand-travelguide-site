// Reads src/data/thailand-neighbourhood-links.csv (generated Trip.com Partner links, stored decoded)
// and writes src/lib/trip-neighbourhoods.ts. Links are kept exactly as generated; encoding happens at render time.
import { readFileSync, writeFileSync } from 'node:fs';
function parse(text) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}
const [head, ...rows] = parse(readFileSync('src/data/thailand-neighbourhood-links.csv', 'utf8')).filter((r) => r.length > 1);
const idx = Object.fromEntries(head.map((h, i) => [h, i]));
const out = {};
for (const r of rows) {
  out[r[idx.slug]] = { area: r[idx.area], city: r[idx.city], link: r[idx.generated_link], fallback: /^fallback: city/.test(r[idx.note] || '') };
}
const [khead, ...krows] = parse(readFileSync('src/data/thailand-keyword-links.csv', 'utf8')).filter((r) => r.length > 1);
const kidx = Object.fromEntries(khead.map((h, i) => [h, i]));
const kout = {};
for (const r of krows) {
  kout[r[kidx.keyword]] = { slug: r[kidx.slug], city: r[kidx.city], link: r[kidx.generated_link], fallback: /city fallback/i.test(r[kidx.note] || '') };
}
writeFileSync('src/lib/trip-neighbourhoods.ts', `// Generated by scripts/sync-neighbourhood-links.mjs from src/data/thailand-neighbourhood-links.csv. Do not edit by hand.
// Trip.com Partner links (SID 334804079, trip_sub1=th_h_<slug>), stored decoded exactly as generated.
export const TRIP_NEIGHBOURHOOD_LINKS: Record<string, { area: string; city: string; link: string; fallback: boolean }> = ${JSON.stringify(out, null, 2)};

// Resort and area hotel searches from src/data/thailand-keyword-links.csv, keyed by search keyword. Stored decoded exactly as generated.
export const TRIP_KEYWORD_LINKS: Record<string, { slug: string; city: string; link: string; fallback: boolean }> = ${JSON.stringify(kout, null, 2)};
`);
console.log(`trip-neighbourhoods: ${rows.length} neighbourhood rows, ${krows.length} keyword rows`);
