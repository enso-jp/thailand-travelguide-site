import { dishesForCity } from './dish-factory';
import type { DishRecord, FoodSpot } from './dish-model';

type Faq = DishRecord['faqs'][number];

export type Spec = {
  slug: string;
  title: string;
  nameLocal: string;
  orderLocal?: string;
  hook: string;
  lede: string;
  description: string;
  taste: string;
  orderName: string;
  orderPhrase: string;
  orderNote: string;
  price: string;
  spice: string;
  diet: string;
  spot: string;
  spotLocal?: string;
  address: string;
  hours?: string;
  spotPrice: string;
  note: string;
  related: string[];
  room: string;
  clock?: string;
  faqs: Faq[];
};

export function pack(city: string, rows: Spec[]): DishRecord[] {
  return dishesForCity(
    city as DishRecord['city'],
    rows.map((row) => {
      const spot: FoodSpot = {
        name: row.spot,
        ...(row.spotLocal ? { nameLocal: row.spotLocal } : {}),
        address: row.address,
        ...(row.hours ? { hours: row.hours } : {}),
        price: row.spotPrice,
        note: row.note,
      };
      return {
        slug: row.slug,
        title: row.title,
        nameLocal: row.nameLocal,
        ...(row.orderLocal ? { orderLocal: row.orderLocal } : {}),
        hook: row.hook,
        lede: row.lede,
        description: row.description,
        taste: row.taste,
        orderName: row.orderName,
        orderPhrase: row.orderPhrase,
        orderNote: row.orderNote,
        price: row.price,
        spice: row.spice,
        diet: row.diet,
        spots: [spot],
        related: row.related,
        photo: `/photos/dish-b5-${city}-${row.slug}.jpg`,
        room: row.room,
        ...(row.clock ? { clock: row.clock } : {}),
        faqs: row.faqs,
      };
    }),
  );
}

