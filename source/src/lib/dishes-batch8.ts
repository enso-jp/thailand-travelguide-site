import { dishesForCity } from './dish-factory';
import type { DishRecord, FoodSpot } from './dish-model';

type Faq = DishRecord['faqs'][number];

type Spec = {
  slug: string;
  title: string;
  nameLocal: string;
  orderLocal: string;
  hook: string;
  lede: string;
  description: string;
  taste: string;
  orderName: string;
  orderPhrase: string;
  orderNote: string;
  price: string;
  spice: string;
  diet: string;
  spot: string;
  address: string;
  hours: string;
  spotPrice: string;
  note: string;
  room: string;
  clock: string;
  related: string[];
  faqs: Faq[];
};

export function pack8(city: string, specs: Spec[]): DishRecord[] {
  return dishesForCity(
    city as DishRecord['city'],
    specs.map((row) => {
      const spot: FoodSpot = {
        name: row.spot,
        address: row.address,
        hours: row.hours,
        price: row.spotPrice,
        note: row.note,
      };
      return {
        slug: row.slug, title: row.title, nameLocal: row.nameLocal, orderLocal: row.orderLocal,
        hook: row.hook, lede: row.lede, description: row.description, taste: row.taste,
        orderName: row.orderName, orderPhrase: row.orderPhrase, orderNote: row.orderNote,
        price: row.price, spice: row.spice, diet: row.diet, spots: [spot], related: row.related,
        photo: `/photos/dish-b8-${city}-${row.slug}.jpg`, room: row.room, clock: row.clock, faqs: row.faqs,
      };
    }),
  );
}

