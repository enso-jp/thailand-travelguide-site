import { dishesForCity } from './dish-factory';
import type { DishRecord, FoodSpot } from './dish-model';

type Faq = DishRecord['faqs'][number];

type Spec = {
  slug: string;
  title: string;
  nameLocal: string;
  orderLocal: string;
  hook: string;
  lede: string;
  description: string;
  taste: string;
  orderName: string;
  orderPhrase: string;
  orderNote: string;
  price: string;
  spice: string;
  diet: string;
  spot: string;
  address: string;
  hours?: string;
  spotPrice: string;
  note: string;
  related: string[];
  room: string;
  clock?: string;
  standalone?: boolean;
  faqs: Faq[];
};

export function pack6(city: string, rows: Spec[]): DishRecord[] {
  return dishesForCity(
    city as DishRecord['city'],
    rows.map((row) => {
      const spot: FoodSpot = {
        name: row.spot,
        address: row.address,
        ...(row.hours ? { hours: row.hours } : {}),
        price: row.spotPrice,
        note: row.note,
      };
      return {
        slug: row.slug,
        title: row.title,
        nameLocal: row.nameLocal,
        orderLocal: row.orderLocal,
        hook: row.hook,
        lede: row.lede,
        description: row.description,
        taste: row.taste,
        orderName: row.orderName,
        orderPhrase: row.orderPhrase,
        orderNote: row.orderNote,
        price: row.price,
        spice: row.spice,
        diet: row.diet,
        spots: [spot],
        related: row.related,
        photo: `/photos/dish-b6-${city}-${row.slug}.jpg`,
        room: row.room,
        ...(row.clock ? { clock: row.clock } : {}),
        ...(row.standalone ? { standalone: true } : {}),
        faqs: row.faqs,
      };
    }),
  );
}

